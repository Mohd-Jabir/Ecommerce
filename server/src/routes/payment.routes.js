
import { Router } from "express";
import { authenticate } from "../middlewares/auth.middleware.js";

import {
  createPaymentOrder,
  verifyPayment,
  paymentStatus,
  razorpayWebhook,
} from "../controllers/payment.controller.js";

const paymentRouter = Router();

/**
 * @swagger
 * tags:
 *   name: Payments
 *   description: Checkout payments and Razorpay integration
 */

/**
 * @swagger
 * /api/v1/payments/webhook:
 *   post:
 *     summary: Receive Razorpay webhook events
 *     description: >
 *       Receives payment events from Razorpay. Authentication is handled
 *       through Razorpay's webhook signature verification, not a user bearer
 *       token. The application must preserve the raw request body for signature
 *       validation.
 *     tags: [Payments]
 *     security: []
 *     parameters:
 *       - in: header
 *         name: X-Razorpay-Signature
 *         required: true
 *         schema:
 *           type: string
 *         description: HMAC signature generated by Razorpay.
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             description: Razorpay webhook event payload.
 *             properties:
 *               event:
 *                 type: string
 *                 example: payment.captured
 *               payload:
 *                 type: object
 *                 additionalProperties: true
 *     responses:
 *       200:
 *         description: Webhook received and processed.
 *       400:
 *         description: Invalid webhook payload or signature.
 *       500:
 *         description: Webhook processing failed.
 */
paymentRouter.post("/webhook", razorpayWebhook);

paymentRouter.use(authenticate);

/**
 * @swagger
 * /api/v1/payments/create-order:
 *   post:
 *     summary: Create a Razorpay payment order
 *     description: Creates a payment attempt for checkout. Requires authentication.
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 *     parameters:
 *       - in: header
 *         name: Idempotency-Key
 *         required: true
 *         schema:
 *           type: string
 *         description: >
 *           Unique checkout key used to prevent duplicate payment attempts
 *           when the same checkout is retried. Confirm the expected header
 *           name against the controller implementation.
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             description: Checkout information accepted by the payment controller.
 *             properties:
 *               orderId:
 *                 type: string
 *                 example: 671a12345678901234567890
 *               checkoutKey:
 *                 type: string
 *                 example: checkout_7c82f91a
 *             additionalProperties: true
 *     responses:
 *       200:
 *         description: Payment order created or an existing checkout attempt returned.
 *       201:
 *         description: Payment order created successfully.
 *       400:
 *         description: Invalid checkout details.
 *       401:
 *         description: Authentication required.
 *       404:
 *         description: Order not found.
 *       409:
 *         description: Checkout conflict or duplicate request.
 *       500:
 *         description: Failed to create the payment order.
 */
paymentRouter.post("/create-order", createPaymentOrder);

/**
 * @swagger
 * /api/v1/payments/verify:
 *   post:
 *     summary: Verify a Razorpay payment
 *     description: >
 *       Verifies payment details submitted after checkout. The server should
 *       validate the Razorpay signature before marking a payment as verified.
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - razorpay_order_id
 *               - razorpay_payment_id
 *               - razorpay_signature
 *             properties:
 *               razorpay_order_id:
 *                 type: string
 *                 example: order_Rzp123456789
 *               razorpay_payment_id:
 *                 type: string
 *                 example: pay_Rzp123456789
 *               razorpay_signature:
 *                 type: string
 *                 example: generated_razorpay_signature
 *     responses:
 *       200:
 *         description: Payment verification processed.
 *       400:
 *         description: Invalid payment details or signature.
 *       401:
 *         description: Authentication required.
 *       404:
 *         description: Payment attempt not found.
 *       409:
 *         description: Payment state conflict.
 *       500:
 *         description: Payment verification failed.
 */
paymentRouter.post("/verify", verifyPayment);

/**
 * @swagger
 * /api/v1/payments/{paymentId}/status:
 *   get:
 *     summary: Get payment status
 *     description: Retrieves the status of a payment attempt belonging to the authenticated user.
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 *     parameters:
 *       - in: path
 *         name: paymentId
 *         required: true
 *         schema:
 *           type: string
 *         description: MongoDB ID of the local payment record.
 *     responses:
 *       200:
 *         description: Payment status retrieved successfully.
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 data:
 *                   $ref: '#/components/schemas/Payment'
 *       401:
 *         description: Authentication required.
 *       403:
 *         description: The payment does not belong to the authenticated user.
 *       404:
 *         description: Payment not found.
 *       500:
 *         description: Failed to retrieve payment status.
 */
paymentRouter.get("/:paymentId/status", paymentStatus);

export default paymentRouter;
